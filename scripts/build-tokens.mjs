#!/usr/bin/env node
/**
 * design/tokens.json (W3C Design Tokens — the format Tokens Studio for Figma reads and writes)
 * → apps/web/src/styles/tokens.css as CSS custom properties. References like {primitive.gold.400} are resolved.
 */
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "apps/web/src/styles/tokens.css";
const tokens = JSON.parse(readFileSync("design/tokens.json", "utf8"));
const get = (path) => path.split(".").reduce((o, k) => o?.[k], tokens);
const resolve = (v) => (typeof v === "string" ? v.replace(/\{([^}]+)\}/g, (_, p) => resolve(get(p)?.$value)) : v);

function flatten(node, prefix, out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$")) continue;
    if (v && typeof v === "object" && "$value" in v) out.push([`--${[...prefix, k].join("-")}`, resolve(v.$value)]);
    else if (v && typeof v === "object") flatten(v, [...prefix, k], out);
  }
  return out;
}

const vars = flatten(tokens, []);
writeFileSync(OUT, `/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */\n:root {\n${vars.map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`);
console.log(`Wrote ${OUT} (${vars.length} tokens)`);
